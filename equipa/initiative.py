@dataclass
class InitiativeRow:
    """In-memory view of an initiatives DB row used to render the header."""

    id: int
    project_id: int
    name: str
    goal: str
    status: str
    created_at: str
    project_codename: str | None = None


@dataclass
class InitiativePlan:
    """Loaded representation of an initiative plan file."""

    path: Path
    initiative_id: int
    raw_text: str

    # ---- factory / persistence -------------------------------------------------

    @classmethod
    def plan_path(cls, repo_path: Path, initiative_id: int) -> Path:
        return Path(repo_path) / ".equipa" / f"initiative-{initiative_id}.md"

    @classmethod
    def _lock_path(cls, plan_path: Path) -> Path:
        return plan_path.with_suffix(plan_path.suffix + ".lock")

    @classmethod
    def load(cls, repo_path: Path, initiative_id: int) -> "InitiativePlan":
        """Read ``.equipa/initiative-<id>.md`` and return a parsed plan.

        Raises ``FileNotFoundError`` if the plan file does not exist —
        callers should usually call :meth:`ensure_exists` first.
        """
        path = cls.plan_path(repo_path, initiative_id)
        if not path.exists():
            raise FileNotFoundError(f"Initiative plan not found: {path}")
        return cls(path=path, initiative_id=initiative_id, raw_text=path.read_text())

    @classmethod
    def ensure_exists(
        cls,
        repo_path: Path,
        initiative_id: int,
        conn: sqlite3.Connection,
    ) -> Path:
        """Create the plan file from the DB row if it does not yet exist.

        Returns the path either way. The DB connection is used read-only.
        """
        path = cls.plan_path(repo_path, initiative_id)
        if path.exists():
            return path

        row = _fetch_initiative_row(conn, initiative_id)
        if row is None:
            raise ValueError(
                f"Cannot create plan: no initiative row for id={initiative_id}"
            )

        content = _render_initial_template(row)
        path.parent.mkdir(parents=True, exist_ok=True)
        _atomic_write(path, content)
        logger.info("Created initiative plan at %s", path)
        return path

    # ---- read -----------------------------------------------------------------

    def to_prompt_context(self) -> str:
        """Return the plan content prefixed with the agent instruction header."""
        return f"{PROMPT_HEADER}\n\n{self.raw_text}"

    # ---- append ---------------------------------------------------------------

    def append_subtask(
        self,
        task_id: int,
        title: str,
        status: str,
        branch: str,
        completed_at: str | datetime | None,
        summary: str,
        decisions: Iterable[tuple[str, str]],
    ) -> None:
        """Append a sub-task entry between the BEGIN/END markers.

        Atomic: write to a temp file in the same directory, then
        ``os.rename`` over the target. A POSIX file lock serialises
        concurrent appends from sibling task dispatches.
        """
        entry = _render_subtask_entry(
            task_id=task_id,
            title=title,
            status=status,
            branch=branch,
            completed_at=completed_at,
            summary=summary,
            decisions=list(decisions),
        )

        lock_path = self._lock_path(self.path)
        with _acquire_lock(lock_path):
            # Re-read inside the lock so we don't clobber a sibling append.
            current = self.path.read_text() if self.path.exists() else self.raw_text
            updated = _insert_before_end_marker(current, entry)
            _atomic_write(self.path, updated)
            self.raw_text = updated


# ---------------------------------------------------------------------------
# Rendering helpers
# ---------------------------------------------------------------------------

def _fetch_initiative_row(
    conn: sqlite3.Connection,
    initiative_id: int,
) -> InitiativeRow | None:
    row = conn.execute(
        """
        SELECT i.id, i.project_id, i.name, i.goal, i.status, i.created_at,
               p.codename
        FROM initiatives i
        LEFT JOIN projects p ON p.id = i.project_id
        WHERE i.id = ?
        """,
        (initiative_id,),
    ).fetchone()
    if row is None:
        return None
    return InitiativeRow(
        id=row[0],
        project_id=row[1],
        name=row[2],
        goal=row[3],
        status=row[4],
        created_at=row[5] or "",
        project_codename=row[6],
    )


def _render_initial_template(row: InitiativeRow) -> str:
    created_date = (row.created_at or "").split(" ", 1)[0] or _today()
    project_label = row.project_codename or f"project_id={row.project_id}"
    return (
        f"# Initiative: {row.name}\n"
        f"\n"
        f"**ID:** {row.id}\n"
        f"**Goal:** {row.goal}\n"
        f"**Status:** {row.status}\n"
        f"**Created:** {created_date}\n"
        f"**Target project:** {project_label}\n"
        f"\n"
        f"---\n"
        f"\n"
        f"## Original Plan\n"
        f"\n"
        f"<!-- Operator: write the initiative's original plan here. -->\n"
        f"\n"
        f"---\n"
        f"\n"
        f"## Sub-tasks\n"
        f"\n"
        f"{HUMAN_EDIT_HINT}\n"
        f"{BEGIN_MARKER}\n"
        f"\n"
        f"{END_MARKER}\n"
    )


def _render_subtask_entry(
    *,
    task_id: int,
    title: str,
    status: str,
    branch: str,
    completed_at: str | datetime | None,
    summary: str,
    decisions: list[tuple[str, str]],
) -> str:
    if isinstance(completed_at, datetime):
        completed_str = completed_at.strftime("%Y-%m-%d %H:%M")
    elif completed_at:
        completed_str = str(completed_at)
    else:
        completed_str = "—"

    lines = [
        f"### #{task_id}: {title}",
        f"**Status:** {status}",
        f"**Branch:** {branch}",
        f"**Completed:** {completed_str}",
        f"**Summary:** {summary or '—'}",
        "**Decisions:**",
    ]
    if decisions:
        for decision, rationale in decisions:
            decision = decision.strip() or "—"
            rationale = rationale.strip()
            if rationale:
                lines.append(f"- {decision} — {rationale}")
            else:
                lines.append(f"- {decision}")
    else:
        lines.append("- (none recorded)")
    lines.append("")  # trailing blank line for separation
    return "\n".join(lines) + "\n"


def _insert_before_end_marker(current: str, entry: str) -> str:
    """Insert ``entry`` immediately before the END marker.

    If markers are missing (file was hand-edited or corrupted), append
    a fresh orchestrator-managed block at the end so the next append
    still has a valid target — but log loudly. We never silently
    overwrite human-edited content above the BEGIN marker.
    """
    if END_MARKER not in current:
        logger.warning(
            "Plan file missing END marker; appending a fresh managed block."
        )
        suffix = (
            f"\n{HUMAN_EDIT_HINT}\n{BEGIN_MARKER}\n\n{entry}{END_MARKER}\n"
        )
        return current.rstrip() + suffix

    head, _, tail = current.rpartition(END_MARKER)
    return f"{head.rstrip()}\n\n{entry}{END_MARKER}{tail}"


def _atomic_write(path: Path, content: str) -> None:
    """Write ``content`` to ``path`` atomically via tempfile + os.rename."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        prefix=path.name + ".",
        suffix=".tmp",
        dir=str(path.parent),
    )
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(content)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp_name, str(path))
    except Exception:
        with contextlib.suppress(FileNotFoundError):
            os.unlink(tmp_name)
        raise


def _today() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


