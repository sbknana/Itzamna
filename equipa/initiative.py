def _fetch_initiative_row(
    conn: sqlite3.Connection,
    initiative_id: int,
) -> InitiativeRow | None:
    row = conn.execute(
        """
        SELECT i.id, i.project_id, i.name, i.goal, i.status, i.created_at,
               p.codename
        FROM initiatives i
        LEFT JOIN projects p ON p.id = i.project_id
        WHERE i.id = ?
        """,
        (initiative_id,),
    ).fetchone()
    if row is None:
        return None
    return InitiativeRow(
        id=row[0],
        project_id=row[1],
        name=row[2],
        goal=row[3],
        status=row[4],
        created_at=row[5] or "",
        project_codename=row[6],
    )


def _render_initial_template(row: InitiativeRow) -> str:
    created_date = (row.created_at or "").split(" ", 1)[0] or _today()
    project_label = row.project_codename or f"project_id={row.project_id}"
    return (
        f"# Initiative: {row.name}\n"
        f"\n"
        f"**ID:** {row.id}\n"
        f"**Goal:** {row.goal}\n"
        f"**Status:** {row.status}\n"
        f"**Created:** {created_date}\n"
        f"**Target project:** {project_label}\n"
        f"\n"
        f"---\n"
        f"\n"
        f"## Original Plan\n"
        f"\n"
        f"<!-- Operator: write the initiative's original plan here. -->\n"
        f"\n"
        f"---\n"
        f"\n"
        f"## Sub-tasks\n"
        f"\n"
        f"{HUMAN_EDIT_HINT}\n"
        f"{BEGIN_MARKER}\n"
        f"\n"
        f"{END_MARKER}\n"
    )


def _render_subtask_entry(
    *,
    task_id: int,
    title: str,
    status: str,
    branch: str,
    completed_at: str | datetime | None,
    summary: str,
    decisions: list[tuple[str, str]],
) -> str:
    if isinstance(completed_at, datetime):
        completed_str = completed_at.strftime("%Y-%m-%d %H:%M")
    elif completed_at:
        completed_str = str(completed_at)
    else:
        completed_str = "—"

    # All agent-supplied fields pass through _sanitize_agent_text to:
    # (a) strip ASCII control chars, (b) neutralise `<!--` so an agent
    # cannot inject orchestrator markers, (c) enforce per-field length
    # caps. This is defence in depth — the S1 untrusted-content fence
    # in to_prompt_context() already protects the *prompt* path; this
    # protects the *file* path (plan-file marker integrity).
    safe_title = _sanitize_agent_text(title, TITLE_MAX_CHARS) or "—"
    safe_summary = _sanitize_agent_text(summary, SUMMARY_MAX_CHARS) or "—"

    lines = [
        f"### #{task_id}: {safe_title}",
        f"**Status:** {status}",
        f"**Branch:** {branch}",
        f"**Completed:** {completed_str}",
        f"**Summary:** {safe_summary}",
        "**Decisions:**",
    ]
    if decisions:
        # S2486-03 fix: cap decisions to MAX_DECISIONS_PER_TASK. Without
        # this cap an agent can emit 100k decision lines (each under the
        # per-field char cap) and balloon the next sibling task's prompt
        # by tens of megabytes — a prompt-budget DOS that bypasses the
        # per-field length budgets the rest of S1 carefully establishes.
        total = len(decisions)
        visible = decisions[:MAX_DECISIONS_PER_TASK]
        for decision, rationale in visible:
            safe_decision = _sanitize_agent_text(
                decision.strip(), DECISION_MAX_CHARS
            ) or "—"
            safe_rationale = _sanitize_agent_text(
                rationale.strip(), RATIONALE_MAX_CHARS
            )
            if safe_rationale:
                lines.append(f"- {safe_decision} — {safe_rationale}")
            else:
                lines.append(f"- {safe_decision}")
        if total > MAX_DECISIONS_PER_TASK:
            remaining = total - MAX_DECISIONS_PER_TASK
            lines.append(f"- [... {remaining} more decisions truncated ...]")
    else:
        lines.append("- (none recorded)")
    lines.append("")  # trailing blank line for separation
    return "\n".join(lines) + "\n"


def _insert_before_end_marker(current: str, entry: str) -> str:
    """Insert ``entry`` immediately before the END marker.

    If markers are missing (file was hand-edited or corrupted), append
    a fresh orchestrator-managed block at the end so the next append
    still has a valid target — but log loudly. We never silently
    overwrite human-edited content above the BEGIN marker.
    """
    if END_MARKER not in current:
        logger.warning(
            "Plan file missing END marker; appending a fresh managed block."
        )
        suffix = (
            f"\n{HUMAN_EDIT_HINT}\n{BEGIN_MARKER}\n\n{entry}{END_MARKER}\n"
        )
        return current.rstrip() + suffix

    head, _, tail = current.rpartition(END_MARKER)
    return f"{head.rstrip()}\n\n{entry}{END_MARKER}{tail}"


def _atomic_write(path: Path, content: str) -> None:
    """Write ``content`` to ``path`` atomically via tempfile + os.rename."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        prefix=path.name + ".",
        suffix=".tmp",
        dir=str(path.parent),
    )
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(content)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp_name, str(path))
        # S2486-07 fix: tempfile.mkstemp creates the temp file with
        # mode 0600, which os.replace preserves. The plan file is
        # intended to be human-readable by the operator (see
        # HUMAN_EDIT_HINT), so widen to 0644 — respect the calling
        # process umask for the bit reset (operator can re-tighten
        # with umask 0177 if running on a shared host).
        try:
            os.chmod(str(path), 0o644)
        except OSError:
            logger.debug("chmod 0644 on %s failed; leaving as-is", path)
    except Exception:
        with contextlib.suppress(FileNotFoundError):
            os.unlink(tmp_name)
        raise


def _today() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


