AGENT_INSTRUCTION_BLOCK = """\
At the END of your task, before signaling completion, emit a final block in this exact format:

<!-- ORCHESTRATOR_OUTPUT -->
SUMMARY: <one-paragraph summary of what you actually did, what worked, what didn't>
DECISIONS:
- <one-line decision> | <one-line rationale>
- <one-line decision> | <one-line rationale>
<!-- /ORCHESTRATOR_OUTPUT -->

The orchestrator parses this block to update the initiative plan file. If you have no
decisions worth recording (purely mechanical task), output `DECISIONS:` with no items.
"""


def build_initiative_prompt_section(
    repo_path: Path,
    initiative_id: int,
    conn: sqlite3.Connection,
) -> str:
    """Build the ``## INITIATIVE CONTEXT`` block injected into agent prompts.

    Ensures the plan file exists, then returns the markdown-formatted
    section. Returns an empty string if anything goes wrong — initiative
    failures must NEVER block task dispatch.
    """
    try:
        InitiativePlan.ensure_exists(repo_path, initiative_id, conn)
        plan = InitiativePlan.load(repo_path, initiative_id)
    except Exception:
        logger.exception(
            "Failed to ensure/load initiative plan for id=%s; "
            "dispatching without initiative context.",
            initiative_id,
        )
        return ""

    return (
        "## INITIATIVE CONTEXT\n\n"
        f"{plan.to_prompt_context()}\n\n"
        f"{AGENT_INSTRUCTION_BLOCK}"
    )


def record_task_completion(
    repo_path: Path,
    initiative_id: int,
    task_id: int,
    title: str,
    status: str,
    branch: str,
    agent_output: str,
    completed_at: datetime | None = None,
) -> bool:
    """Parse the agent output and append a sub-task entry to the plan file.

    Returns True if the plan was updated, False if a fatal error
    prevented the update. Callers should NOT treat a False return as
    cause to abort the task — initiative tracking is best-effort.
    """
    try:
        path = InitiativePlan.plan_path(repo_path, initiative_id)
        if not path.exists():
            logger.warning(
                "Plan file missing at completion time for initiative=%s; "
                "skipping append.",
                initiative_id,
            )
            return False

        parsed = parse_orchestrator_output(agent_output)
        if parsed is None:
            logger.warning(
                "Agent output had no ORCHESTRATOR_OUTPUT block for task=%s; "
                "appending placeholder.",
                task_id,
            )
            summary = "(no orchestrator output block emitted by agent)"
            decisions: list[tuple[str, str]] = []
        else:
            if parsed.malformed:
                logger.warning(
                    "Agent ORCHESTRATOR_OUTPUT block malformed for task=%s; "
                    "captured best-effort.",
                    task_id,
                )
            summary = parsed.summary or "(empty summary)"
            decisions = parsed.decisions

        plan = InitiativePlan.load(repo_path, initiative_id)
        plan.append_subtask(
            task_id=task_id,
            title=title,
            status=status,
            branch=branch,
            completed_at=completed_at or datetime.now(timezone.utc),
            summary=summary,
            decisions=decisions,
        )
        return True
    except Exception:
        logger.exception(
            "Failed to record task completion to initiative plan "
            "(task=%s, initiative=%s)",
            task_id,
            initiative_id,
        )
        return False
