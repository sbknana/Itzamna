"""EQUIPA initiative plan file helpers (Phase 1).

An *initiative* is a long-horizon piece of work composed of multiple
dispatched tasks. Phase 1 introduces shared working memory across those
tasks via a per-initiative plan file at::

    <target-repo>/.equipa/initiative-<id>.md

The orchestrator is the SINGLE WRITER to the plan file. Agents read it
(as they read any other repo file) but never write to it; they emit a
structured ``ORCHESTRATOR_OUTPUT`` block which the orchestrator parses
and appends to the plan.

Key invariants:

* Everything ABOVE the ``<!-- BEGIN ORCHESTRATOR-MANAGED -->`` marker is
  human-editable; the orchestrator never touches it.
* Everything BETWEEN the BEGIN and END markers is orchestrator-exclusive
  and append-only (newest sub-task at the bottom).
* Writes are atomic: ``tempfile + os.rename``. The plan file is never
  left in a half-written state, even on crash.
* A file-level lock (``fcntl.flock`` on POSIX) serialises parallel
  appends from concurrent task dispatches in the same initiative.
  Windows callers must serialise externally — see :func:`_acquire_lock`.

Public surface::

    InitiativePlan.load(repo_path, initiative_id) -> InitiativePlan
    InitiativePlan.ensure_exists(repo_path, initiative_id, conn) -> Path
    plan.append_subtask(task_id, title, status, branch, completed_at,
                        summary, decisions) -> None
    plan.to_prompt_context() -> str

    parse_orchestrator_output(raw_text) -> ParsedOutput | None

Copyright 2026 Forgeborn
"""

from __future__ import annotations

import contextlib
import logging
import os
import re
import sqlite3
import tempfile
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable, Iterator

logger = logging.getLogger(__name__)


BEGIN_MARKER = "<!-- BEGIN ORCHESTRATOR-MANAGED -->"
END_MARKER = "<!-- END ORCHESTRATOR-MANAGED -->"
HUMAN_EDIT_HINT = (
    "<!-- AUTO-MAINTAINED BY ORCHESTRATOR BELOW THIS LINE — do not edit by hand -->"
)

PROMPT_HEADER = (
    "You are working in a long-horizon EQUIPA initiative. The plan below "
    "is shared working memory across every task in this initiative — read "
    "it, build on prior decisions, and avoid re-treading dead-ends already "
    "recorded as failed approaches. Do NOT edit this file directly; the "
    "orchestrator will append your structured output after you finish."
)

# Per-field length caps applied in _render_subtask_entry to bound the
# damage of an over-large agent-supplied field (defence in depth on top
# of the S1 untrusted-content wrapper). The values are deliberately
# generous — a normal SUMMARY is one paragraph (<1 KB), a normal decision
# line is well under 200 chars — but tight enough that a malicious agent
# cannot smuggle a megabyte of prompt-injection payload through the
# plan file into the next sibling task's system prompt.
SUMMARY_MAX_CHARS = 4096
DECISION_MAX_CHARS = 512
RATIONALE_MAX_CHARS = 512
TITLE_MAX_CHARS = 512
TRUNCATION_SUFFIX = "... [truncated]"

# S2486-03 fix: per-task decisions list cap. Normal tasks emit <10
# decisions; 20 is generous enough for legitimate complex tasks while
# blocking the 50k-line prompt-budget DOS described in the review.
# When exceeded, the first MAX_DECISIONS_PER_TASK are kept and the rest
# are replaced by a single truncation marker line.
MAX_DECISIONS_PER_TASK = 20

# Control characters: ASCII 0x00-0x1F EXCEPT \n (0x0A) and \t (0x09).
# Allowed because legitimate multi-line summaries use newlines; everything
# else (NUL, ESC, BEL, ...) is stripped to prevent terminal-control
# spoofing and binary smuggling into the markdown plan file.
#
# S2486-04 fix: also strip Unicode bidirectional override characters
# (U+202A–U+202E, U+2066–U+2069) and zero-width characters (U+200B–U+200D,
# U+2060, U+FEFF). These enable the "Trojan Source" / CVE-2021-42574
# class of attack: an agent embeds U+202E (RTL OVERRIDE) inside a
# SUMMARY and the operator sees rendered markdown with reversed text
# direction, masking what the agent actually wrote.
_CTRL_CHARS_RE = re.compile(
    "["
    "\x00-\x08\x0b-\x1f\x7f"
    "\u202a-\u202e"  # bidi override: LRE, RLE, PDF, LRO, RLO
    "\u2066-\u2069"  # bidi isolate: LRI, RLI, FSI, PDI
    "\u200b-\u200d"  # zero-width: ZWSP, ZWNJ, ZWJ
    "\u2060"          # word joiner
    "\ufeff"          # zero-width no-break space / BOM
    "]"
)

# HTML comment opener — we neutralise it in agent-supplied fields so an
# adversarial agent cannot inject a literal `<!-- END ORCHESTRATOR-MANAGED -->`
# (or a NEW BEGIN marker) into the plan file via SUMMARY/DECISIONS and
# corrupt the orchestrator's append point. Replacing the second hyphen
# with the Unicode non-breaking hyphen (U+2011) keeps the field visually
# identical in rendered markdown while breaking the HTML comment lexer.
_HTML_COMMENT_OPENER = "<!--"
_HTML_COMMENT_OPENER_NEUTRAL = "<!‑‑"  # second hyphen → U+2011 non-breaking hyphen


def _sanitize_agent_text(value: str | None, max_chars: int) -> str:
    """Sanitise an agent-supplied string before it lands in the plan file.

    Three independent transforms (all defensive, all additive on top of
    the S1 untrusted-content fence wrapping `to_prompt_context()`):

    1. Strip ASCII control characters except ``\\n`` and ``\\t``.
    2. Neutralise literal ``<!--`` sequences so they cannot spoof the
       orchestrator's BEGIN/END markers (the second hyphen becomes a
       Unicode non-breaking hyphen — visually identical, lexically inert).
    3. Truncate to ``max_chars`` with a clearly-marked suffix.

    Order matters: strip control chars BEFORE truncation so we count
    visible chars, not invisible bytes. Neutralise markers BEFORE
    truncation so a partial ``<!--`` at the cut point cannot reform.
    """
    if not value:
        return ""
    s = _CTRL_CHARS_RE.sub("", str(value))
    s = s.replace(_HTML_COMMENT_OPENER, _HTML_COMMENT_OPENER_NEUTRAL)
    if len(s) > max_chars:
        head_len = max(0, max_chars - len(TRUNCATION_SUFFIX))
        s = s[:head_len] + TRUNCATION_SUFFIX
    return s


