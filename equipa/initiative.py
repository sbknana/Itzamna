"""EQUIPA initiative plan file helpers (Phase 1).

An *initiative* is a long-horizon piece of work composed of multiple
dispatched tasks. Phase 1 introduces shared working memory across those
tasks via a per-initiative plan file at::

    <target-repo>/.equipa/initiative-<id>.md

The orchestrator is the SINGLE WRITER to the plan file. Agents read it
(as they read any other repo file) but never write to it; they emit a
structured ``ORCHESTRATOR_OUTPUT`` block which the orchestrator parses
and appends to the plan.

Key invariants:

* Everything ABOVE the ``<!-- BEGIN ORCHESTRATOR-MANAGED -->`` marker is
  human-editable; the orchestrator never touches it.
* Everything BETWEEN the BEGIN and END markers is orchestrator-exclusive
  and append-only (newest sub-task at the bottom).
* Writes are atomic: ``tempfile + os.rename``. The plan file is never
  left in a half-written state, even on crash.
* A file-level lock (``fcntl.flock`` on POSIX) serialises parallel
  appends from concurrent task dispatches in the same initiative.
  Windows callers must serialise externally — see :func:`_acquire_lock`.

Public surface::

    InitiativePlan.load(repo_path, initiative_id) -> InitiativePlan
    InitiativePlan.ensure_exists(repo_path, initiative_id, conn) -> Path
    plan.append_subtask(task_id, title, status, branch, completed_at,
                        summary, decisions) -> None
    plan.to_prompt_context() -> str

    parse_orchestrator_output(raw_text) -> ParsedOutput | None

Copyright 2026 Forgeborn
"""

from __future__ import annotations

import contextlib
import logging
import os
import re
import sqlite3
import tempfile
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable, Iterator

logger = logging.getLogger(__name__)


BEGIN_MARKER = "<!-- BEGIN ORCHESTRATOR-MANAGED -->"
END_MARKER = "<!-- END ORCHESTRATOR-MANAGED -->"
HUMAN_EDIT_HINT = (
    "<!-- AUTO-MAINTAINED BY ORCHESTRATOR BELOW THIS LINE — do not edit by hand -->"
)

PROMPT_HEADER = (
    "You are working in a long-horizon EQUIPA initiative. The plan below "
    "is shared working memory across every task in this initiative — read "
    "it, build on prior decisions, and avoid re-treading dead-ends already "
    "recorded as failed approaches. Do NOT edit this file directly; the "
    "orchestrator will append your structured output after you finish."
)


# ---------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------

ORCHESTRATOR_OUTPUT_RE = re.compile(
    r"<!--\s*ORCHESTRATOR_OUTPUT\s*-->(.*?)<!--\s*/ORCHESTRATOR_OUTPUT\s*-->",
    re.DOTALL,
)


@dataclass
class ParsedOutput:
    """Parsed result of an agent's ``ORCHESTRATOR_OUTPUT`` block."""

    summary: str = ""
    decisions: list[tuple[str, str]] = field(default_factory=list)
    malformed: bool = False


def parse_orchestrator_output(raw_text: str) -> ParsedOutput | None:
    """Parse the agent's final ``ORCHESTRATOR_OUTPUT`` block.

    Returns ``None`` if the block is absent (callers should log a warning
    and append a placeholder entry). If multiple blocks are present, the
    LAST one wins — agents may emit revised drafts.

    Tolerates: missing pipe separator (whole line is treated as the
    decision text, rationale empty), extra whitespace, missing or empty
    ``DECISIONS:`` section.
    """
    if not raw_text:
        return None

    matches = ORCHESTRATOR_OUTPUT_RE.findall(raw_text)
    if not matches:
        return None

    body = matches[-1]
    result = ParsedOutput()

    # Split into SUMMARY and DECISIONS sections by scanning line-by-line.
    summary_lines: list[str] = []
    decision_lines: list[str] = []
    section: str | None = None
    for raw_line in body.splitlines():
        line = raw_line.rstrip()
        stripped = line.strip()
        if not stripped:
            if section == "summary":
                summary_lines.append("")
            continue
        if stripped.upper().startswith("SUMMARY:"):
            section = "summary"
            after = stripped.split(":", 1)[1].strip()
            if after:
                summary_lines.append(after)
            continue
        if stripped.upper().startswith("DECISIONS:"):
            section = "decisions"
            after = stripped.split(":", 1)[1].strip()
            if after:
                decision_lines.append(after)
            continue
        if section == "summary":
            summary_lines.append(stripped)
        elif section == "decisions":
            decision_lines.append(stripped)

    result.summary = " ".join(s for s in summary_lines if s).strip()

    for entry in decision_lines:
        # Bullet markers are optional; strip them.
        entry = entry.lstrip("-*•").strip()
        if not entry:
            continue
        if "|" in entry:
            decision, rationale = entry.split("|", 1)
            result.decisions.append((decision.strip(), rationale.strip()))
        else:
            # Tolerate missing separator.
            result.decisions.append((entry, ""))
            result.malformed = True

    if not result.summary:
        result.malformed = True

    return result


# ---------------------------------------------------------------------------
# File lock helpers
# ---------------------------------------------------------------------------

@contextlib.contextmanager
def _acquire_lock(lock_path: Path) -> Iterator[None]:
    """Exclusive file lock for serialising plan-file writes.

    POSIX implementation uses ``fcntl.flock``. The lock is released
    automatically when the context exits (including on exception).

    On Windows ``fcntl`` is unavailable; callers there must serialise
    externally (e.g. a process-wide threading.Lock keyed on the path).
    This module intentionally does NOT silently no-op the lock on
    Windows — a corruption-prone fallback is worse than a clear error
    at import time when someone tries to run EQUIPA orchestrator on a
    platform we have not validated.
    """
    try:
        import fcntl  # POSIX-only
    except ImportError as exc:  # pragma: no cover - non-POSIX platform
        raise RuntimeError(
            "Plan-file locking requires fcntl (POSIX). On Windows, "
            "serialise InitiativePlan.append_subtask calls externally."
        ) from exc

    lock_path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(str(lock_path), os.O_RDWR | os.O_CREAT, 0o644)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX)
        yield
    finally:
        try:
            fcntl.flock(fd, fcntl.LOCK_UN)
        finally:
            os.close(fd)


