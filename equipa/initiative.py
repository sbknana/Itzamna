ORCHESTRATOR_OUTPUT_RE = re.compile(
    r"<!--\s*ORCHESTRATOR_OUTPUT\s*-->(.*?)<!--\s*/ORCHESTRATOR_OUTPUT\s*-->",
    re.DOTALL,
)


@dataclass
class ParsedOutput:
    """Parsed result of an agent's ``ORCHESTRATOR_OUTPUT`` block."""

    summary: str = ""
    decisions: list[tuple[str, str]] = field(default_factory=list)
    malformed: bool = False


def parse_orchestrator_output(raw_text: str) -> ParsedOutput | None:
    """Parse the agent's final ``ORCHESTRATOR_OUTPUT`` block.

    Returns ``None`` if the block is absent (callers should log a warning
    and append a placeholder entry). If multiple blocks are present, the
    LAST one wins — agents may emit revised drafts.

    Tolerates: missing pipe separator (whole line is treated as the
    decision text, rationale empty), extra whitespace, missing or empty
    ``DECISIONS:`` section.
    """
    if not raw_text:
        return None

    matches = ORCHESTRATOR_OUTPUT_RE.findall(raw_text)
    if not matches:
        return None

    body = matches[-1]
    result = ParsedOutput()

    # Split into SUMMARY and DECISIONS sections by scanning line-by-line.
    summary_lines: list[str] = []
    decision_lines: list[str] = []
    section: str | None = None
    for raw_line in body.splitlines():
        line = raw_line.rstrip()
        stripped = line.strip()
        if not stripped:
            if section == "summary":
                summary_lines.append("")
            continue
        if stripped.upper().startswith("SUMMARY:"):
            section = "summary"
            after = stripped.split(":", 1)[1].strip()
            if after:
                summary_lines.append(after)
            continue
        if stripped.upper().startswith("DECISIONS:"):
            section = "decisions"
            after = stripped.split(":", 1)[1].strip()
            if after:
                decision_lines.append(after)
            continue
        if section == "summary":
            summary_lines.append(stripped)
        elif section == "decisions":
            decision_lines.append(stripped)

    result.summary = " ".join(s for s in summary_lines if s).strip()

    for entry in decision_lines:
        # Bullet markers are optional; strip them.
        entry = entry.lstrip("-*•").strip()
        if not entry:
            continue
        if "|" in entry:
            decision, rationale = entry.split("|", 1)
            result.decisions.append((decision.strip(), rationale.strip()))
        else:
            # Tolerate missing separator.
            result.decisions.append((entry, ""))
            result.malformed = True

    if not result.summary:
        result.malformed = True

    return result


# ---------------------------------------------------------------------------
# File lock helpers
# ---------------------------------------------------------------------------

@contextlib.contextmanager
def _acquire_lock(lock_path: Path) -> Iterator[None]:
    """Exclusive file lock for serialising plan-file writes.

    POSIX implementation uses ``fcntl.flock``. The lock is released
    automatically when the context exits (including on exception).

    On Windows ``fcntl`` is unavailable; callers there must serialise
    externally (e.g. a process-wide threading.Lock keyed on the path).
    This module intentionally does NOT silently no-op the lock on
    Windows — a corruption-prone fallback is worse than a clear error
    at import time when someone tries to run EQUIPA orchestrator on a
    platform we have not validated.

    LIMITATION (S2-INIT-05): ``fcntl.flock`` is HOST-LOCAL. It serialises
    concurrent initiative runs that share the same kernel/filesystem (the
    normal single-host orchestrator deployment), but it provides NO mutual
    exclusion across DIFFERENT hosts pointing at the same repo over a
    network/shared filesystem (NFS flock semantics are unreliable, and two
    separate machines do not share a lock table at all). If EQUIPA is ever
    run from multiple hosts against one repo, two initiative dispatches can
    both acquire "the" lock and race on plan-file writes / wave dispatch.
    Cross-host mutual exclusion would require a DB advisory lock (e.g. a row
    in TheForge claimed with an atomic compare-and-set on ``initiatives``)
    layered ON TOP of this host-local flock — not yet implemented because the
    current deployment is single-host.
    """
    try:
        import fcntl  # POSIX-only
    except ImportError as exc:  # pragma: no cover - non-POSIX platform
        raise RuntimeError(
            "Plan-file locking requires fcntl (POSIX). On Windows, "
            "serialise InitiativePlan.append_subtask calls externally."
        ) from exc

    lock_path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(str(lock_path), os.O_RDWR | os.O_CREAT, 0o644)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX)
        yield
    finally:
        try:
            fcntl.flock(fd, fcntl.LOCK_UN)
        finally:
            os.close(fd)


